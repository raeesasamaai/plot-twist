export function shuffle<T>(input: T[]): T[] {
  const out = [...input];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
export function fallbackQuestions(): Question[] {
  return shuffle(
    bank.map(([text, correct, b, c, d, category], i) => {
      const choices = shuffle([correct, b, c, d]);
      return {
        id: `original-${i}`,
        text,
        choices,
        correct: choices.indexOf(correct),
        category,
      };
    }),
  ).slice(0, 15);
}
